/// Script command: load the pack that holds one palette, then copy it into the next palette slot.
// Nonmatching: the two operand words are split with the right instructions but scheduled separately
// (the target merges both loads into one `ldmib`) and the palette arguments land in other registers.
// The local declaration order below is the one that reproduces the retail register allocation.
s32 func_ov003_02083478(Ov003BgResState* state) {
    const Ov003ResCmd* cmd       = state->cursor;
    u16                packIndex = (cmd->operands0 & 0xFFFF0000) >> 16;
    u16                srcIndex  = (u16)cmd->operands0;
    u16                palStart  = (cmd->operands1 & 0xFFFF0000) >> 16;
    u16                palCount  = (u16)cmd->operands1;
    void*              source;

    if (state->data != NULL) {
        DatMgr_ReleaseData(state->data);
    }
    state->data = DatMgr_LoadPackEntry(1, NULL, 0, state->iden, packIndex, 0);
    source      = Data_GetPackEntryData(state->data, srcIndex);
    if (state->paletteCount < 3) {
        if (state->engine == 0) {
            state->palettes[state->paletteCount] =
                PaletteMgr_AllocPalette(g_PaletteManagers[0], source, 0, palStart, palCount);
            PaletteMgr_Flush(g_PaletteManagers[0], state->palettes[state->paletteCount]);
        } else {
            state->palettes[state->paletteCount] =
                PaletteMgr_AllocPalette(g_PaletteManagers[1], source, 0, palStart, palCount);
            PaletteMgr_Flush(g_PaletteManagers[1], state->palettes[state->paletteCount]);
        }
        state->paletteCount++;
    }
    state->cursor = &state->cursor[1];
    return 1;
}

/// Script command: copy one character (tile) block of the current pack into BG VRAM.
s32 func_ov003_020835d4(Ov003BgResState* state) {
    const Ov003ResCmd* cmd       = state->cursor;
    u16                bgIndex   = (u16)cmd->operands0;
    u16                packIndex = (cmd->operands0 & 0xFFFF0000) >> 16;
    u16                srcIndex  = (u16)cmd->operands1;
    u16                charTile  = (cmd->operands1 & 0xFFFF0000) >> 16;
    s32                charDest;
    s32                size;
    void*              source;

    if (state->data != NULL) {
        DatMgr_ReleaseData(state->data);
    }
    state->data = DatMgr_LoadPackEntry(1, NULL, 0, state->iden, packIndex, 0);
    source      = Data_GetPackEntryData(state->data, srcIndex);
    if (state->engine == 0) {
        if (bgIndex == 1) {
            charDest = G2_GetBG1CharPtr() + (charTile << 5);
        } else {
            charDest = G2_GetBG2CharPtr() + (charTile << 5);
        }
    } else {
        if (bgIndex == 1) {
            charDest = G2S_GetBG1CharPtr() + (charTile << 6);
        } else {
            charDest = func_02036974() + (charTile << 6);
        }
    }
    size = (((const CombatBgTiles*)source)->header & ~0xFF) >> 8;
    if ((((const CombatBgTiles*)source)->format & 0xF0) == 0) {
        size -= 4;
    }
    func_02001b44(7, charDest, ((const CombatBgTiles*)source)->pixels, size);
    state->cursor = &state->cursor[1];
    return 1;
}

/// Script command: set up one of the two sprite slots and queue its palette.
// Nonmatching: register allocation around the slot setup (the target keeps `state` in r7 and the
// cursor in r0, and merges two adjacent state loads that we keep apart).
s32 func_ov003_02083700(Ov003BgResState* state) {
    const Ov003ResSlotCmd* cmd       = (const Ov003ResSlotCmd*)state->cursor;
    const void*            anims     = cmd->anims;
    u32                    wC        = cmd->slot;
    u32                    w10       = cmd->palette;
    u16                    bgIndex   = (u16)cmd->bg;
    u16                    slotIndex = (u16)wC;
    u16                    charTile  = (wC & 0xFFFF0000) >> 16;
    u8                     palStart  = (u8)((w10 & 0xFFFF0000) >> 16);
    u8                     palCount  = (u8)w10;
    s32                    charDest;
    Ov003SpriteSlot*       slot;

    if (state->engine == 0) {
        if (bgIndex == 1) {
            charDest = G2_GetBG1CharPtr() + (charTile << 5);
        } else {
            charDest = G2_GetBG2CharPtr() + (charTile << 5);
        }
    } else {
        if (bgIndex == 1) {
            charDest = G2S_GetBG1CharPtr() + (charTile << 6);
        } else {
            charDest = func_02036974() + (charTile << 6);
        }
    }
    slot = &state->slots[slotIndex];
    func_ov003_020d3eb4(slot, state->iden, cmd->anims, (void*)charDest, 1, 0);
    if (palCount != 0) {
        func_ov003_020d3f44(slot, 0, state->iden, state->engine, palStart, palCount);
    }
    state->cursor = (const Ov003ResCmd*)&((const Ov003ResSlotCmd*)state->cursor)[1];
    return 1;
}

/// Places the main engine's camera on its path entry and aims it at the battle centre.
// Nonmatching: the target computes the half-width as `(0x200 - x) << 15 >> 16` (a fixed-point
// scale) where mwcc folds our `/ 2` into a single `asr #1`.
void func_ov003_0208380c(void) {
    const Ov003CameraPathPos* pos = data_ov003_020da2c0[data_ov003_020e71b8->unk3D7C0[0].pathId].pos;
    Ov003Camera*              cam = &data_ov003_020e71b8->unk3D7C0[0];
    s16                       bottom;
    s16                       top;
    s32                       halfX;

    halfX  = (0x200 - pos->unk_00) / 2;
    bottom = pos->unk_04;
    top    = pos->unk_02;
    if (top <= bottom) {
        top = bottom;
    }
    func_ov003_02083a2c(0, halfX, 0x200 - top, 0x200 - halfX, 0x1E8);

    cam->rotation = FX_Atan2Idx((pos->unk_02 - pos->unk_04) << 12, cam->unk_0C);
    cam->posX     = ((0x200 - pos->unk_02) << 12) - cam->unk_08;
    cam->shakeY   = -0x28000;
    cam->posY     = ((0x200 - pos->unk_06) << 12) - cam->unk_08;
    cam->shakeX   = cam->posY;
}

/// Places the sub engine's camera on its path entry.
void func_ov003_020838d8(void) {
    const Ov003CameraPathPos* pos  = data_ov003_020d9c94[data_ov003_020e71b8->unk3D7C0[1].pathId].pos;
    Ov003Camera*              cam  = &data_ov003_020e71b8->unk3D7C0[1];
    s16                       left = 0x200 - pos->unk_00;

    func_ov003_02083a2c(1, 0x70, (s16)(left - pos->unk_02), 0x190, left);
    cam->shakeY = pos->unk_04 << 12;
}

