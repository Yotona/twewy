// Steps a wrapping cursor with the D-Pad. Returns TRUE if it moved.
s32 func_ov030_020b139c(s16* cursor, s32 count) {
    s32 moved = 0;

    if (SysControl.buttonState.holdButtons & INPUT_BUTTON_RIGHT) {
        *cursor += 1;
        if (*cursor >= count) {
            *cursor = 0;
        }
        moved = 1;
    } else if (SysControl.buttonState.holdButtons & INPUT_BUTTON_LEFT) {
        moved = 1;
        *cursor -= 1;
        if (*cursor < 0) {
            *cursor = count - 1;
        }
    }

    return moved;
}

